import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const sourceDir = path.join(rootDir, 'source');
const prodDir = path.join(rootDir, 'deployable');
const devDir = path.join(rootDir, 'dev');
const zipPath = path.join(rootDir, 'scamhisn-extension-prod.zip');

function copyDirRecursive(src, dest, excludeRelPaths = new Set(), base = src) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const relPath = path.relative(base, srcPath);
    if (excludeRelPaths.has(relPath)) continue;
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath, excludeRelPaths, base);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function buildTarget({ outDir, isDev }) {
  fs.rmSync(outDir, { recursive: true, force: true });

  // Production build excludes content.js completely so Check Everything code isn't shipped
  const excludes = isDev ? new Set() : new Set(['src/content.js']);
  copyDirRecursive(sourceDir, outDir, excludes);

  // Write environment-specific config.js
  const configContent = `// Auto-generated by scripts/build.mjs (${isDev ? 'PRIVATE DEV' : 'PRODUCTION'})
export const EXTENSION_CONFIG = {
  DEV_MODE: ${isDev ? 'true' : 'false'},
  DEFAULT_API_BASE: '${isDev ? 'http://localhost:3001' : 'https://scamhisn-ai.onrender.com'}',
  MAX_AUTO_LINKS_PER_PAGE: 6,
};
`;
  fs.writeFileSync(path.join(outDir, 'src/config.js'), configContent, 'utf8');

  // Write environment-specific manifest.json
  const manifest = JSON.parse(fs.readFileSync(path.join(sourceDir, 'manifest.json'), 'utf8'));
  if (isDev) {
    manifest.name = 'ScamHisn AI (DEV — Private Testing)';
    manifest.content_scripts = [
      {
        matches: ['http://*/*', 'https://*/*'],
        js: ['src/content.js'],
        run_at: 'document_idle',
      },
    ];
  } else {
    // Production strictly strips localhost host permission and keeps minimal permissions
    manifest.host_permissions = ['https://*.onrender.com/*'];
  }

  fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
}

buildTarget({ outDir: prodDir, isDev: false });
buildTarget({ outDir: devDir, isDev: true });

// Package deployable/ as Chrome Web Store ready .zip
fs.rmSync(zipPath, { force: true });
execSync(`cd "${prodDir}" && zip -rq "${zipPath}" .`, { stdio: 'inherit' });

console.log('✓ Built production extension:', prodDir);
console.log('✓ Built private dev extension:', devDir);
console.log('✓ Packaged Chrome Web Store zip:', zipPath);
